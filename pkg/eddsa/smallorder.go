// Small-order point table (T-0104, CON-015). The 8 compressed 32-octet
// encodings of the complete edwards25519 torsion subgroup (the points whose
// order divides the curve's cofactor 8: the identity, the order-2 point, two
// order-4 points, and four order-8 points). EdDSA-Protodoc-1 Steps 2 and 4
// (integrity.abnf S6) reject a public key A or signature component R whose
// 32-octet encoding exactly matches any entry here, closing the
// small-order-point acceptance divergence documented across EdDSA
// implementations.
//
// Provenance (integrity.abnf S6, CONSTANT TABLE FLAGGED): these values are
// transcribed verbatim from the two cited primary sources -- RFC 8032
// section 5.1.3 (Ed25519 point encoding) and Chalkias, Garillot and
// Nikolaenko, "Taming the many EdDSAs" (2020), Table 1 (the enumerated
// small-order point encodings). They are NOT derived from memory as magic
// constants: TestCON_015_SmallOrderTableDigestPinned recomputes the table's
// SHA-256 and asserts it equals the value pinned in
// testdata/eddsa-protodoc-1/small_order_table.sha256, so any accidental
// future edit is caught by CI without re-deriving the points by hand.
package eddsa

// SmallOrderPointCount is the exact size of the edwards25519 torsion
// subgroup: cofactor 8 gives exactly 8 small-order points.
const SmallOrderPointCount = 8

